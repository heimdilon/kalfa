async fn tls_cikisini_bosalt(
    baglanti: &mut ServerConnection,
    soket: &mut TcpStream,
) -> io::Result<()> {
    while baglanti.wants_write() {
        let mut tls_cikti = Vec::new();
        baglanti.write_tls(&mut tls_cikti)?;
        if !tls_cikti.is_empty() {
            soket.write_all(&tls_cikti).await?;
        }
    }
    soket.flush().await
}

/// Bir `TcpStream` üzerinde TLS el sıkışmasını ve HTTP/1.1 istek okumasını tamamlar,
/// verilen işleyiciyle üretilen HTTP yanıt baytlarını TLS üzerinden gönderip kapatır.
pub async fn tls_http_baglanti_isle<F>(
    mut soket: TcpStream,
    tls_ayari: Arc<rustls::ServerConfig>,
    isleyici: F,
) -> io::Result<()>
where
    F: FnOnce(String, HashMap<String, String>, Vec<u8>) -> Vec<u8>,
{
    let mut baglanti =
        ServerConnection::new(tls_ayari).map_err(|e| io::Error::other(e.to_string()))?;
    let mut tampon = Vec::with_capacity(4096);
    let mut ag_parca = [0u8; 4096];

    let baslik_sonu = loop {
        tls_cikisini_bosalt(&mut baglanti, &mut soket).await?;

        if let Some(konum) = tampon.windows(4).position(|w| w == b"\r\n\r\n") {
            break konum + 4;
        }

        if baglanti.wants_read() {
            let n = soket.read(&mut ag_parca).await?;
            if n == 0 {
                return Ok(());
            }
            let mut imlec = io::Cursor::new(&ag_parca[..n]);
            baglanti.read_tls(&mut imlec)?;
            baglanti
                .process_new_packets()
                .map_err(|e| io::Error::other(e.to_string()))?;
        }

        let mut okuma_parca = [0u8; 2048];
        while let Ok(n) = baglanti.reader().read(&mut okuma_parca) {
            if n == 0 {
                break;
            }
            tampon.extend_from_slice(&okuma_parca[..n]);
        }
    };

    let baslik_metni = String::from_utf8_lossy(&tampon[..baslik_sonu]);
    let ilk_satir = baslik_metni.lines().next().unwrap_or_default().to_owned();
    let mut basliklar = HashMap::new();
    for satir in baslik_metni.lines().skip(1) {
        if let Some((ad, deger)) = satir.split_once(':') {
            basliklar.insert(ad.trim().to_ascii_lowercase(), deger.trim().to_owned());
        }
    }
    let icerik_uzunlugu: usize = basliklar
        .get("content-length")
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);

    let mut govde = tampon[baslik_sonu..].to_vec();
    while govde.len() < icerik_uzunlugu {
        if baglanti.wants_read() {
            let n = soket.read(&mut ag_parca).await?;
            if n == 0 {
                break;
            }
            let mut imlec = io::Cursor::new(&ag_parca[..n]);
            baglanti.read_tls(&mut imlec)?;
            baglanti
                .process_new_packets()
                .map_err(|e| io::Error::other(e.to_string()))?;
        }
        let mut okuma_parca = [0u8; 2048];
        while let Ok(n) = baglanti.reader().read(&mut okuma_parca) {
            if n == 0 {
                break;
            }
            govde.extend_from_slice(&okuma_parca[..n]);
        }
    }
    govde.truncate(icerik_uzunlugu);

    let yanit_baytlari = isleyici(ilk_satir, basliklar, govde);
    baglanti.writer().write_all(&yanit_baytlari)?;
    tls_cikisini_bosalt(&mut baglanti, &mut soket).await?;
    baglanti.send_close_notify();
    let _ = tls_cikisini_bosalt(&mut baglanti, &mut soket).await;
    let _ = soket.shutdown().await;
    Ok(())
}
